def _load_or_create_secret() -> str:
    """签名密钥：环境变量优先，否则落盘生成一次并复用（重启后会话不失效）。"""
    from_env = _env("WB_SECRET_KEY")
    if from_env:
        return from_env
    if SECRET_PATH.exists():
        existing = SECRET_PATH.read_text(encoding="utf-8").strip()
        if existing:
            return existing
    generated = secrets.token_urlsafe(48)
    SECRET_PATH.write_text(generated, encoding="utf-8")
    try:
        SECRET_PATH.chmod(0o600)
    except OSError:
        pass
    return generated


def _load_or_create_password() -> tuple[str, bool]:
    """控制台密码：环境变量优先，否则落盘生成一次。

    返回 (密码, 是否为本次自动生成)。绝不允许空密码——这是公网部署最容易踩的坑。
    """
    from_env = _env("WB_PASSWORD")
    if from_env:
        return from_env, False
    if PASSWORD_PATH.exists():
        existing = PASSWORD_PATH.read_text(encoding="utf-8").strip()
        if existing:
            return existing, False
    generated = secrets.token_urlsafe(12)
    PASSWORD_PATH.write_text(generated, encoding="utf-8")
    try:
        PASSWORD_PATH.chmod(0o600)
    except OSError:
        pass
    return generated, True


SECRET_KEY = _load_or_create_secret()
PASSWORD, PASSWORD_AUTOGENERATED = _load_or_create_password()

