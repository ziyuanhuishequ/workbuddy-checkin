#!/usr/bin/env python3
"""启动入口：python run.py"""

import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import uvicorn  # noqa: E402

from app import config  # noqa: E402
from app.main import app  # noqa: E402


def main() -> None:
    reload_enabled = os.environ.get("WB_RELOAD", "").strip() in ("1", "true", "yes")
    print(f"\n  {config.APP_NAME} v{config.VERSION}")
    print(f"  监听地址   http://{config.HOST}:{config.PORT}")
    print(f"  数据目录   {config.DATA_DIR}")
    print(f"  时区       UTC{config.TZ_OFFSET_HOURS:+d}")
    if config.PASSWORD_AUTOGENERATED:
        print(f"\n  ⚠ 已自动生成控制台密码：{config.PASSWORD}")
        print(f"    （同时保存在 {config.PASSWORD_PATH}）\n")
    else:
        print(f"  控制台密码 已从环境变量 / {config.PASSWORD_PATH} 读取\n")

    uvicorn.run(
        "app.main:app" if reload_enabled else app,
        host=config.HOST,
        port=config.PORT,
        log_level="info",
        reload=reload_enabled,
        access_log=False,
    )


if __name__ == "__main__":
    main()
